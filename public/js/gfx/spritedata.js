function registerNpc(name, spec) {
  const v = spec.custom || villager(spec);
  for (const dir of ['down', 'up', 'side']) {
    SPRITE_DEFS[`${name}_${dir}_0`] = v[dir];
    SPRITE_DEFS[`${name}_${dir}_1`] = v[dir];
  }
}

