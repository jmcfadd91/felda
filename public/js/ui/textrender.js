export const CHAR_W = 6; // 5px glyph + 1px spacing
export const CHAR_H = 8;

const ORDER = Object.keys(GLYPHS);
const sheets = new Map(); // color -> canvas

function bakeSheet(color) {
  const c = document.createElement('canvas');
  c.width = ORDER.length * CHAR_W;
  c.height = CHAR_H;
  const ctx = c.getContext('2d');
  ctx.fillStyle = color;
  ORDER.forEach((ch, i) => {
    const rows = GLYPHS[ch];
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 5; x++) {
        if (rows[y][x] === '1') ctx.fillRect(i * CHAR_W + x, y, 1, 1);
      }
    }
  });
  return c;
}

function sheet(color) {
  let s = sheets.get(color);
  if (!s) { s = bakeSheet(color); sheets.set(color, s); }
  return s;
}

const INDEX = new Map(ORDER.map((ch, i) => [ch, i]));

// Draw a single line of text. Unknown chars render as spaces.
export function drawText(ctx, text, x, y, color = '#fff', shadow = null) {
  const up = String(text).toUpperCase();
  if (shadow) drawText(ctx, text, x + 1, y + 1, shadow);
  const s = sheet(color);
  for (let i = 0; i < up.length; i++) {
    const idx = INDEX.get(up[i]);
    if (idx === undefined || up[i] === ' ') continue;
    ctx.drawImage(s, idx * CHAR_W, 0, CHAR_W, CHAR_H, x + i * CHAR_W, y, CHAR_W, CHAR_H);
  }
}

export function textWidth(text) {
  return String(text).length * CHAR_W;
}

export function drawTextCentered(ctx, text, cx, y, color = '#fff', shadow = null) {
  drawText(ctx, text, Math.floor(cx - textWidth(text) / 2), y, color, shadow);
}

// Word-wrap into lines of at most maxChars.
export function wrapText(text, maxChars) {
  const words = String(text).split(' ');
  const lines = [];
  let line = '';
  for (const w of words) {
    if (line && line.length + 1 + w.length > maxChars) {
      lines.push(line);
      line = w;
    } else {
      line = line ? `${line} ${w}` : w;
    }
  }
  if (line) lines.push(line);
  return lines;
}
